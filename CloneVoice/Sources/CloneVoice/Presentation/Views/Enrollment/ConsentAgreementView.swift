import SwiftUI

/// Tier 1: Explicit legal consent and synthetic media disclosure.
public struct ConsentAgreementView: View {
    @Binding var profileName: String
    var onAccept: () -> Void
    var onCancel: () -> Void
    
    @State private var hasAgreedToTerms = false
    
    public init(
        profileName: Binding<String>,
        onAccept: @escaping () -> Void,
        onCancel: @escaping () -> Void
    ) {
        self._profileName = profileName
        self.onAccept = onAccept
        self.onCancel = onCancel
    }
    
    public var body: some View {
        VStack(spacing: 20) {
            // Title Header
            VStack(spacing: 8) {
                Image(systemName: "checkmark.shield.fill")
                    .font(.system(size: 40))
                    .foregroundColor(DesignTokens.Colors.acousticCyan)
                
                Text("Voice Enrollment Consent")
                    .font(.system(size: 22, weight: .bold, design: .rounded))
                
                Text("App Store Guideline 5.1 & 5.2 Ethical Voice Protection")
                    .font(.system(size: 13))
                    .foregroundColor(.secondary)
            }
            .padding(.top, 16)
            
            // Name Input
            GlassCard(cornerRadius: DesignTokens.Radii.medium) {
                VStack(alignment: .leading, spacing: 8) {
                    Text("PROFILE IDENTIFIER")
                        .font(.system(size: 11, weight: .bold, design: .rounded))
                        .foregroundColor(.secondary)
                    
                    TextField("Enter profile name (e.g. My Studio Voice)", text: $profileName)
                        .font(.system(size: 16, weight: .medium))
                        .textFieldStyle(.plain)
                }
                .padding(14)
            }
            
            // Terms Scroll Box
            GlassCard(cornerRadius: DesignTokens.Radii.large) {
                ScrollView {
                    VStack(alignment: .leading, spacing: 12) {
                        Text("1. Exclusive Personal Ownership")
                            .font(.system(size: 14, weight: .bold))
                        Text("You affirm and warrant that you are the sole biological owner of the voice being recorded, or hold express legal authorization. Creating clones of third parties without explicit legal consent is strictly prohibited.")
                            .font(.system(size: 13))
                            .foregroundColor(.secondary)
                        
                        Text("2. C2PA Provenance & Watermarking")
                            .font(.system(size: 14, weight: .bold))
                        Text("All synthesized media generated by Clone Voice embeds cryptographic Content Credentials (C2PA) certifying algorithmic origin, preventing deepfake impersonation.")
                            .font(.system(size: 13))
                            .foregroundColor(.secondary)
                        
                        Text("3. Hardware Biometric Lock")
                            .font(.system(size: 14, weight: .bold))
                        Text("Your voice profile will be secured using Apple's Secure Enclave. Speech generation requires live Face ID / Touch ID verification.")
                            .font(.system(size: 13))
                            .foregroundColor(.secondary)
                    }
                    .padding(16)
                }
                .frame(maxHeight: 200)
            }
            
            // Checkbox
            Toggle(isOn: $hasAgreedToTerms) {
                Text("I agree to the Voice Terms & Biometric Verification.")
                    .font(.system(size: 13, weight: .medium))
            }
            .toggleStyle(SwitchToggleStyle(tint: DesignTokens.Colors.acousticCyan))
            
            Spacer()
            
            // Action
            HStack(spacing: 12) {
                Button("Cancel", action: onCancel)
                    .font(.system(size: 16, weight: .medium))
                    .foregroundColor(.secondary)
                    .frame(maxWidth: .infinity)
                
                LiquidGlassButton(
                    title: "Proceed to Recording",
                    systemImage: "mic.fill",
                    style: .primary,
                    action: onAccept
                )
                .disabled(!hasAgreedToTerms || profileName.trimmingCharacters(in: .whitespaces).isEmpty)
                .opacity((hasAgreedToTerms && !profileName.trimmingCharacters(in: .whitespaces).isEmpty) ? 1.0 : 0.5)
            }
        }
        .padding(24)
    }
}
