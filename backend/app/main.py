import json
from contextlib import asynccontextmanager
from typing import Optional
from fastapi import FastAPI, UploadFile, File, Form, Depends, HTTPException, status
from fastapi.responses import StreamingResponse
from fastapi.middleware.cors import CORSMiddleware

from app.config import settings
from app.models import HealthResponse, SynthesisSettingsModel
from app.voxcpm_engine import VoxCPMEngine
from app.c2pa_signer import C2PASigner
from app.security import verify_app_attest, compute_acoustic_hash, secure_ephemeral_wipe

# Global engine instance
engine: Optional[VoxCPMEngine] = None

@asynccontextmanager
async def lifespan(app: FastAPI):
    global engine
    print(f"[{settings.app_name}] Booting VoxCPM2 inference worker...")
    engine = VoxCPMEngine(model_name=settings.model_name, device=settings.device)
    yield
    print(f"[{settings.app_name}] Gracefully shutting down...")

app = FastAPI(
    title=settings.app_name,
    version=settings.version,
    lifespan=lifespan
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/v1/health", response_model=HealthResponse)
async def health_check():
    """Returns backend status, GPU model, and VRAM availability."""
    global engine
    if engine is None:
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail="Engine initializing")
    return engine.get_status()

@app.post("/v1/synthesis/stream")
async def stream_synthesis(
    text: str = Form(...),
    settings_json: Optional[str] = Form(None, alias="settings"),
    reference_audio: UploadFile = File(...),
    _: bool = Depends(verify_app_attest)
):
    """
    Streams synthesized 48kHz speech chunks generated by VoxCPM2.
    Uses strictly verified VoxCPM2 parameters: cfg_value, inference_timesteps, denoise, seed.
    Processes audio ephemerally with zero data retention.
    """
    global engine
    if engine is None:
        raise HTTPException(status_code=503, detail="Inference engine not ready")
        
    synth_settings = SynthesisSettingsModel()
    if settings_json:
        try:
            parsed = json.loads(settings_json)
            synth_settings = SynthesisSettingsModel(**parsed)
        except Exception:
            pass
            
    text = text.strip()
    if not text:
        raise HTTPException(status_code=400, detail="Text parameter cannot be empty.")
        
    raw_audio = bytearray(await reference_audio.read())
    if len(raw_audio) < 44:
        raise HTTPException(status_code=400, detail="Invalid audio file: Payload too small or corrupt.")
    if len(raw_audio) > 50 * 1024 * 1024:
        raise HTTPException(status_code=413, detail="Payload Too Large: Reference audio must be under 50MB.")
        
    voice_hash = compute_acoustic_hash(bytes(raw_audio))
    
    async def audio_stream_generator():
        try:
            async for chunk in engine.stream_cloned_speech(
                text=text,
                reference_audio_bytes=bytes(raw_audio),
                cfg_value=synth_settings.cfg_value,
                inference_timesteps=synth_settings.inference_timesteps,
                denoise=synth_settings.denoise,
                seed=synth_settings.seed
            ):
                yield chunk
        finally:
            if synth_settings.zero_retention:
                secure_ephemeral_wipe(raw_audio)

    return StreamingResponse(
        audio_stream_generator(),
        media_type="audio/wav",
        headers={
            "Transfer-Encoding": "chunked",
            "X-Voice-Acoustic-Hash": voice_hash[:16],
            "X-Zero-Retention-Enforced": "true" if synth_settings.zero_retention else "false"
        }
    )

if __name__ == "__main__":
    import uvicorn
    uvicorn.run("app.main:app", host=settings.host, port=settings.port, reload=True)
